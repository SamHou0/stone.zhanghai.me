def main():
    ids = {p[0] for p in PEOPLE}
    rels = {}
    for a, b, label in RELATIONS:
        if a not in ids or b not in ids:
            raise SystemExit(f"unknown relation endpoint: {a} {b}")
        rels.setdefault(a, []).append((b, label))
        rels.setdefault(b, []).append((a, label))

    people = []
    for pid, name, aliases, house, role, desc in PEOPLE:
        people.append(
            {
                "id": pid,
                "name": name,
                "aliases": aliases,
                "house": house,
                "role": role,
                "desc": desc,
                "relations": [
                    {"id": rid, "name": next(p[1] for p in PEOPLE if p[0] == rid), "label": label}
                    for rid, label in rels.get(pid, [])
                ],
            }
        )

    graph_ids = {n[0] for n in GRAPH_NODES}
    edges = []
    seen = set()
    for a, b, label in EXTRA_EDGES + RELATIONS:
        if a not in graph_ids or b not in graph_ids:
            continue
        key = tuple(sorted((a, b))) + (label,)
        if key in seen:
            continue
        seen.add(key)
        edges.append({"from": a, "to": b, "label": label})
    nodes = [{"id": n[0], "x": n[1], "y": n[2], "group": n[3]} for n in GRAPH_NODES]

    data = (
        "/* 由 _build_characters.py 生成，请勿手工修改。 */\n"
        "window.HLM_CHARACTERS = "
        + json.dumps(people, ensure_ascii=False, separators=(",", ":"))
        + ";\nwindow.HLM_GRAPH = "
        + json.dumps({"nodes": nodes, "edges": edges}, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    with open(os.path.join(BOOK, "characters-data.js"), "w", encoding="utf-8") as f:
        f.write(data)
    print("people", len(people), "relations", sum(len(p["relations"]) for p in people), "graph nodes", len(nodes), "edges", len(edges))


if __name__ == "__main__":
    main()
